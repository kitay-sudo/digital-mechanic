"""Демо-стенд (DEMO_STAND=1): эксперты входят в админку по логину и паролю, показанным на экране входа.

Чтобы стенд работал у всех до конца проверки, на нём запрещено то, что ломает его для других:
удалить или переиндексировать руководства заказчика, изменить или удалить демо-механиков (их PIN видны
на экране входа), сохранить адреса сервисов и сменить модель. Всё остальное в админке работает:
журнал, разбор случаев, смена, загрузка и удаление своих руководств, свои механики.
"""
from __future__ import annotations

import os

# Начало текста ошибки: по нему интерфейс узнаёт запрет демо-стенда и показывает свою панель
PREFIX = "На демо-стенде"
MAX_UPLOADS = 5


def enabled() -> bool:
    return os.environ.get("DEMO_STAND", "").strip().lower() in ("1", "true", "yes")


def admin_access() -> dict | None:
    """Логин и пароль администратора для экрана входа. Только на демо-стенде."""
    if not enabled():
        return None
    from .auth import admin_credentials

    login, password = admin_credentials()
    return {"login": login, "password": password}


def locked(what: str) -> str:
    # Заголовок панели уже говорит «запрещено системой», здесь — что именно и почему
    return f"{PREFIX} нельзя {what}, чтобы стенд работал у всех экспертов. На сервере заказчика это делает администратор."

def manuals_block(vehicle: dict) -> str:
    lines = [f"- {m.id}: {m.designation} ({m.short}, {m.pages} стр.)" for m in manuals_for_engine(vehicle["engine_model"])]
    return "\n".join(lines) if lines else "- нет документов"


def turn_context(vehicle: dict, session_id: str, saved: dict | None) -> str:
    session = fleet.get_session(vehicle, session_id)
    lines = [
        "[Контекст]",
        f"Машина: {fleet.title_of(vehicle)}, госномер {vehicle['vehicle_id']}, гаражный номер {vehicle.get('garage_no')}.",
        f"Двигатель: {vehicle['engine_model']}, топливо: {vehicle.get('fuel')}.",
        "Руководства этого двигателя (manual_id: обозначение):",
        manuals_block(vehicle),
        f"Проверок в истории: {len(vehicle['sessions'])}. Выбрана проверка {session_id}"
        + (f" от {session.get('checked_at')}." if session else "."),
    ]
    if saved:
        lines.append("Результат выбранной проверки уже получен:")
        lines.append(json.dumps({"diagnosis": saved["diagnosis"], "assessment": saved["assessment"]}, ensure_ascii=False))
    else:
        lines.append("Результат выбранной проверки ещё не запрошен.")
    return "\n".join(lines)


def render_for_history(message: dict) -> str:
    """Короткая запись прошлого сообщения агента для контекста следующего хода."""
    parts = [message.get("text") or ""]
    answer = message.get("answer") or {}
    for key, label in (("checks", "Проверки"), ("repair", "Ремонт")):
        for item in answer.get(key) or []:
            refs = ", ".join(f"{r['manual_id']} стр. {r['pdf_page']}" for r in item.get("refs", []))
            parts.append(f"{label}: {item['text']} [{refs}]")
    for text in answer.get("hypotheses") or []:
        parts.append(f"Гипотеза: {text}")
    draft = message.get("draft")
    if draft:
        parts.append(f"Черновик заявки {draft['draft_id']}: статус {draft['status']}, приоритет {draft.get('urgency')}.")
    ticket = message.get("ticket")
    if ticket:
        parts.append(f"Создана заявка {ticket['ticket_id']}.")
    return "\n".join(p for p in parts if p)


def recommendation_text(vehicle: dict, diagnosis: dict, reason: str) -> str:
    """Текст рекомендации на дефектовку, когда заявку в ТОиР отправить нельзя (П10)."""
    code = diagnosis.get("anomaly_type")
    unit = rules.FAULTS.get(code or "", {}).get("unit", "узел по типу неисправности")
    return (
        f"Рекомендация на дефектовку. Машина {fleet.title_of(vehicle)}, госномер {vehicle['vehicle_id']}, "
        f"двигатель {vehicle['engine_model']}. Проверка {diagnosis.get('session_id')} от {diagnosis.get('checked_at')}. "
        f"Результат акустической проверки: {diagnosis.get('anomaly_title')} ({code}), "
        f"оценка отклонения {rules.fmt(diagnosis.get('anomaly_score'))}, уверенность {rules.fmt(diagnosis.get('confidence'))}, "
        f"качество записи: {rules.QUALITY_LABELS.get(diagnosis.get('signal_quality'), diagnosis.get('signal_quality'))}. "
        f"Признаки: {diagnosis.get('description')}. {reason} "
        f"Рекомендуется дефектовка узла: {unit}."
    )

def profile_line(profile: dict | None) -> str:
    """Строка контекста про механика: уровень и язык ответа (адаптивность, кик-офф 26.11)."""
    profile = profile or {}
    language = LANGUAGES.get(profile.get("language"), LANGUAGES["ru"])
    level = LEVELS.get(profile.get("level"), LEVELS["expert"])
    return f"Механик: уровень «{level}», язык ответа: {language}."


def turn_context(vehicle: dict, session_id: str, saved: dict | None, profile: dict | None = None) -> str:
    session = fleet.get_session(vehicle, session_id)
    lines = [
        "[Контекст]",
        f"Машина: {fleet.title_of(vehicle)}, госномер {vehicle['vehicle_id']}, гаражный номер {vehicle.get('garage_no')}.",
        f"Двигатель: {vehicle['engine_model']}, топливо: {vehicle.get('fuel')}.",
        "Руководства этого двигателя (manual_id: обозначение):",
        manuals_block(vehicle),
        f"Проверок в истории: {len(vehicle['sessions'])}. Выбрана проверка {session_id}"
        + (f" от {session.get('checked_at')}." if session else "."),
    ]
    if saved:
        lines.append("Результат выбранной проверки уже получали раньше, он ниже. Для вопросов по нему повторный запрос не нужен. "
                     "Если механик просит получить или показать результат диагностики, вызови get_diagnosis: "
                     "карточку результата система показывает только после этого вызова.")
        lines.append(json.dumps({"diagnosis": saved["diagnosis"], "assessment": saved["assessment"]}, ensure_ascii=False))
    else:
        lines.append("Результат выбранной проверки ещё не запрошен.")
    lines.append(profile_line(profile))
    return "\n".join(lines)


def render_for_history(message: dict) -> str:
    """Короткая запись прошлого сообщения агента для контекста следующего хода."""
    parts = [message.get("text") or ""]
    answer = message.get("answer") or {}
    for key, label in (("checks", "Проверки"), ("repair", "Ремонт")):
        for item in answer.get(key) or []:
            refs = ", ".join(f"{r['manual_id']} стр. {r['pdf_page']}" for r in item.get("refs", []))
            parts.append(f"{label}: {item['text']} [{refs}]")
    for text in answer.get("hypotheses") or []:
        parts.append(f"Гипотеза: {text}")
    for block in answer.get("conflicts") or []:
        places = ", ".join(f"{s['ref']['manual_id']} стр. {s['ref']['pdf_page']}" for s in block["statements"])
        parts.append(f"Расхождение в документах: {block['topic']} [{places}]")
    draft = message.get("draft")
    if draft:
        parts.append(f"Черновик заявки {draft['draft_id']}: статус {draft['status']}, приоритет {draft.get('urgency')}.")
    ticket = message.get("ticket")
    if ticket:
        parts.append(f"Создана заявка {ticket['ticket_id']}.")
    return "\n".join(p for p in parts if p)


def _when(value: str | None) -> str:
    """Дата проверки для текста механику: 28.10.2026 14:20."""
    try:
        return datetime.fromisoformat(value).strftime("%d.%m.%Y %H:%M")
    except (TypeError, ValueError):
        return str(value or "")


def mismatch_text(vehicle: dict, diagnosis: dict) -> str:
    """Текст для передачи дальше, когда результат модели не подходит двигателю машины (П16)."""
    return (
        f"Расхождение данных диагностики. Машина {fleet.title_of(vehicle)}, госномер {vehicle['vehicle_id']}, "
        f"двигатель {vehicle['engine_model']} ({vehicle.get('fuel')}). Проверка {diagnosis.get('session_id')} "
        f"от {_when(diagnosis.get('checked_at'))}. Модель диагностики вернула тип «{diagnosis.get('anomaly_title')}» "
        f"({diagnosis.get('anomaly_type')}), который не подходит этому двигателю. Результат считается ошибкой модели, "
        "а не диагнозом. Рекомендуется повторить проверку. Если сомнения в состоянии двигателя остаются, "
        "провести дефектовку без привязки к этому типу. Заявка в ТОиР до уточнения данных не оформлена."
    )


def recommendation_text(vehicle: dict, diagnosis: dict, reason: str) -> str:
    """Текст рекомендации на дефектовку, когда заявку в ТОиР отправить нельзя (П10)."""
    code = diagnosis.get("anomaly_type")
    unit = rules.FAULTS.get(code or "", {}).get("unit", "узел по типу неисправности")
    return (
        f"Рекомендация на дефектовку. Машина {fleet.title_of(vehicle)}, госномер {vehicle['vehicle_id']}, "
        f"двигатель {vehicle['engine_model']}. Проверка {diagnosis.get('session_id')} от {_when(diagnosis.get('checked_at'))}. "
        f"Результат акустической проверки: {diagnosis.get('anomaly_title')} ({code}), "
        f"оценка отклонения {rules.fmt(diagnosis.get('anomaly_score'))}, уверенность {rules.fmt(diagnosis.get('confidence'))}, "
        f"качество записи: {rules.QUALITY_LABELS.get(diagnosis.get('signal_quality'), diagnosis.get('signal_quality'))}. "
        f"Признаки: {diagnosis.get('description')}. {reason} "
        f"Рекомендуется дефектовка узла: {unit}."
    )

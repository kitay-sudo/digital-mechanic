def profile_line(profile: dict | None) -> str:
    """Строка контекста про механика: кто пишет (смены) и уровень подачи (адаптивность, кик-офф 26.11)."""
    level = LEVELS.get((profile or {}).get("level"), LEVELS["expert"])
    name = ((profile or {}).get("name") or "").strip()
    who = f"Сейчас пишет механик {name}" if name else "Сейчас пишет механик (фамилия не указана)"
    line = f"{who}, уровень «{level}»."
    if level == LEVELS["novice"]:
        # Напоминание рядом с вопросом: правило из инструкции модель держит слабее (отчёт проверки 28.11)
        line += (" Пиши для новичка: в summary объясни, что происходит и почему это важно; каждый термин при первом "
                 "упоминании расшифруй в скобках; к каждому шагу добавь, зачем он нужен или где находится узел.")
    return line


def _parse_time(value: str | None) -> datetime | None:
    try:
        return datetime.fromisoformat(value) if value else None
    except ValueError:
        return None


def when(value: str | None) -> str:
    """Дата и время для контекста: «27.11.2026 18:40»."""
    moment = _parse_time(value)
    if moment is None:
        return "время неизвестно"
    if moment.tzinfo is not None:
        moment = moment.astimezone(_local_tz())
    return moment.strftime("%d.%m.%Y %H:%M")


def _ago(value: str | None) -> str:
    moment = _parse_time(value)
    if moment is None:
        return ""
    hours = (datetime.now(moment.tzinfo) - moment).total_seconds() / 3600
    if hours < 1:
        return "меньше часа назад"
    if hours < 48:
        return f"{int(hours)} ч назад"
    return f"{int(hours // 24)} дн. назад"



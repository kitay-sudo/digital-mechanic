def manuals_block(vehicle: dict) -> str:
    lines = [f"- {m.id}: {m.designation} ({m.short}, {m.pages} стр.)" for m in manuals_for_engine(vehicle["engine_model"])]
    return "\n".join(lines) if lines else "- нет документов"


